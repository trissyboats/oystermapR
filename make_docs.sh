#!/bin/bash
# Regenerate the roxygen documentation and the reference manual PDF.
#
# Run this after ANY change to roxygen comments in R/, and always before a CRAN
# submission. It is the step that turns the @-tags in R/*.R into man/*.Rd, into
# NAMESPACE, and into oystermapR_reference.pdf.
#
# Usage: bash make_docs.sh
#
# Needs: devtools/roxygen2, and a LaTeX installation for the PDF (tinytex is
# enough -- tinytex::install_tinytex() if you do not have one).

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"

PKG_VERSION=$(grep -m1 '^Version:' DESCRIPTION | sed 's/Version:[[:space:]]*//')
echo "=== oystermapR $PKG_VERSION -- regenerating documentation ==="
echo ""

# -- Step 1: roxygen -> man/*.Rd + NAMESPACE ----------------------------------
echo "--- Step 1: devtools::document() ---"
Rscript --vanilla -e "devtools::document('.')"
echo ""

# -- Step 2: tidy the generated Rd --------------------------------------------
echo "--- Step 2: fix_rd.py ---"
python3 fix_rd.py
echo ""

# -- Step 3: reference manual PDF ---------------------------------------------
# Rd2pdf refuses to overwrite, so the old manual goes first.
echo "--- Step 3: R CMD Rd2pdf ---"
rm -f oystermapR_reference.pdf
R CMD Rd2pdf . \
  --no-preview \
  --force \
  --output=oystermapR_reference.pdf \
  --title="oystermapR: Predict and Map Oyster Growth Suitability from Environmental Data"
echo ""

echo "=== Done ==="
echo "  man/           $(ls man/*.Rd 2>/dev/null | wc -l | tr -d ' ') Rd files"
echo "  NAMESPACE      $(grep -c '^export(' NAMESPACE) exports, $(grep -c '^S3method(' NAMESPACE) S3 methods"
echo "  reference PDF  oystermapR_reference.pdf"
echo ""
echo "Not regenerated by this script (they are written by hand):"
echo "  oystermapR_user_guide.docx      oystermapR_rationale.pdf"
echo "  SeafloorSpeciesmapper_Capabilities.docx / .pdf"
